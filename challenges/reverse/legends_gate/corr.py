#!/usr/bin/env python3

# The XOR Key used throughout the challenge
KEY = 0x22

# Password Bytes: "L45_L3y3nd45!"
secret = [0x6e, 0x16, 0x17, 0x7d, 0x6e, 0x11, 0x5b, 0x11, 0x4c, 0x46, 0x16, 0x17, 0x03]

# Flag Bytes: INFODAYS{RE_15_NOT_GU3551NG_2026}
# (Extracted from Ghidra stack blocks and corrected for Little-Endian)
flag = [
    0x6b, 0x6c, 0x64, 0x6d, 0x66, 0x63, 0x7b, 0x71, 
    0x59, 0x70, 0x67, 0x7d, 0x13, 0x17, 0x7d, 0x6c, 
    0x6d, 0x76, 0x7d, 0x65, 0x77, 0x11, 0x17, 0x17, 
    0x13, 0x6c, 0x65, 0x7d, 0x10, 0x12, 0x10, 0x14, 0x5f
]

def decrypt(data):
    return "".join([chr(b ^ KEY) for b in data])

print(f"[*] Recovered Password: {decrypt(secret)}")
print(f"[*] Recovered Flag    : {decrypt(flag)}")
