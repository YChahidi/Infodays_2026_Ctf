#include <stdio.h>
#include <string.h>
#include <stdlib.h>
#include <sys/ptrace.h>
#include <unistd.h>

/**
 * XOR Key: 0x22
 * '[' (0x5b) ^ 0x22 = 0x79 ('y' or 'Y' depending on case)
 * '+' (0x2b) ^ 0x22 = 0x09
 * ']' (0x5d) ^ 0x22 = 0x7f
 */

void secure_gate() {
    if (ptrace(PTRACE_TRACEME, 0, 1, 0) < 0) {
        write(1, "Debugger detected!\n", 19);
        exit(1);
    }
}

void decrypt_print(const unsigned char* encrypted, size_t len) {
    for(size_t i = 0; i < len; i++) {
        putchar(encrypted[i] ^ 0x22);
    }
}

int main() {
    char input[64];
    
    // "--- ENSA Agadir: Legendary Access ---" (Length: 37)
    unsigned char welcome[] = {
        0x0f, 0x0f, 0x0f, 0x02, 0x67, 0x6c, 0x71, 0x63, 0x02, 0x63, 
        0x45, 0x43, 0x46, 0x4b, 0x50, 0x18, 0x02, 0x6e, 0x47, 0x45, 
        0x47, 0x4c, 0x46, 0x43, 0x50, 0x5b, 0x02, 0x63, 0x41, 0x41, 
        0x47, 0x51, 0x51, 0x02, 0x0f, 0x0f, 0x0f
    };

    // "Code: " (Length: 6)
    unsigned char prompt[] = {0x61, 0x4d, 0x46, 0x47, 0x18, 0x02};

    // "[+] Legend Verified! Flag: " (Length: 27)
    unsigned char success_msg[] = {
        0x79, 0x09, 0x7f, 0x02, 0x6e, 0x47, 0x45, 0x47, 0x4c, 0x46, 
        0x02, 0x74, 0x47, 0x50, 0x4b, 0x44, 0x4b, 0x47, 0x46, 0x03, 
        0x02, 0x64, 0x4e, 0x43, 0x45, 0x18, 0x02
    };

    // "INFODAYS{RE_15_NOT_GU3551NG_2026}" (Length: 33)
    unsigned char flag[] = {
        0x6b, 0x6c, 0x64, 0x6d, 0x66, 0x63, 0x7b, 0x71, 0x59, 0x70, 
        0x67, 0x7d, 0x13, 0x17, 0x7d, 0x6c, 0x6d, 0x76, 0x7d, 0x65, 
        0x77, 0x11, 0x17, 0x17, 0x13, 0x6c, 0x65, 0x7d, 0x10, 0x12, 
        0x10, 0x14, 0x5f
    };

    unsigned char secret[] = {0x6e, 0x16, 0x17, 0x7d, 0x6e, 0x11, 0x5b, 0x11, 0x4c, 0x46, 0x16, 0x17, 0x03};

    secure_gate();

    decrypt_print(welcome, 37);
    putchar('\n');
    
    decrypt_print(prompt, 6);
    fflush(stdout);

    if (fgets(input, sizeof(input), stdin)) {
        input[strcspn(input, "\n")] = 0;

        if (strlen(input) == 13) {
            int valid = 1;
            for (int i = 0; i < 13; i++) {
                if ((input[i] ^ 0x22) != secret[i]) {
                    valid = 0;
                    break;
                }
            }

            if (valid) {
                decrypt_print(success_msg, 27);
                decrypt_print(flag, 33);
                putchar('\n');
            } else {
                // "[!] Unauthorized." (Length: 16)
                unsigned char unauth[] = {0x79, 0x03, 0x7f, 0x02, 0x77, 0x4c, 0x43, 0x56, 0x4a, 0x4d, 0x50, 0x4b, 0x58, 0x47, 0x46, 0x0c};
                decrypt_print(unauth, 16);
                putchar('\n');
            }
        }
    }
    return 0;
}
